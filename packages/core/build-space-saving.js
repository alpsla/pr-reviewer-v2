/**
 * Space-saving build script
 * Used when disk space is limited
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

console.log('🚀 Running space-saving build process...');

// First, clean up space
try {
  console.log('🧹 Cleaning up to free space...');
  execSync('rm -rf node_modules/.cache');
  execSync('rm -rf .turbo');
  execSync('rm -rf coverage');
  execSync('rm -rf dist');
} catch (err) {
  console.warn('⚠️ Cleanup warning:', err.message);
}

// Build JavaScript
try {
  console.log('📦 Building JavaScript bundles...');
  execSync('npx tsup src/index.ts --format cjs,esm --no-dts --clean');
} catch (err) {
  console.error('❌ JavaScript build failed:', err.message);
  process.exit(1);
}

// Create minimal declaration file
try {
  console.log('📝 Creating minimal declaration files...');
  
  const distDir = path.join(__dirname, 'dist');
  if (!fs.existsSync(distDir)) {
    fs.mkdirSync(distDir, { recursive: true });
  }
  
  // Create index.d.ts
  const content = `/**
 * PR Reviewer Core Library
 * Minimal TypeScript declarations (space-saving version)
 */

// Auth module
export * from './auth';

// VCS module 
export * from './vcs';

// Repository module
export * from './repository';

// Utility modules
export * from './utils';
`;

  fs.writeFileSync(path.join(distDir, 'index.d.ts'), content);
  
  // Create subdirectory TypeScript declarations
  const subdirs = ['auth', 'vcs', 'repository', 'utils'];
  
  subdirs.forEach(dir => {
    const subdir = path.join(distDir, dir);
    if (!fs.existsSync(subdir)) {
      fs.mkdirSync(subdir, { recursive: true });
    }
    
    const indexContent = `/**
 * ${dir} module declarations
 * Generated by space-saving build
 */
export {};
`;
    
    fs.writeFileSync(path.join(subdir, 'index.d.ts'), indexContent);
  });
  
  console.log('✅ Created minimal declaration files successfully');
} catch (err) {
  console.error('❌ Declaration generation failed:', err.message);
  process.exit(1);
}

console.log('🎉 Space-saving build completed successfully!');
